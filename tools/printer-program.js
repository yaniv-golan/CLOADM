// A printer test program for the built-in firmware (no ROMs): it prints through the machine's own printer hardware,
// for the browser check's printer-panel group (tools/browser-check.js printerPanelChecks).
//   dragon: the parallel printer: the byte on PIA0 port B ($FF02), a strobe pulse on PIA1 PA1 ($FF20 bit 1)
//           (js/machines/sam.js; tests/dragon-printer.test.js)
//   coco:   the serial printer on the bit-banger, PIA1 PA1 ($FF20 bit 1): 600 baud, 8 data bits, no parity, a stop
//           bit, timed by a delay loop at the CoCo's 0.894886 MHz (1491.5 cycles a bit)
// It prints `bytes` (any values: a $FF, a NUL, a TAB, a long line), then, with `slow`, "LINE nnnn" and a CR forever,
// one line about every tenth of a second of machine time, the count in BCD at COUNT (2 bytes). Without `slow` it stops
// in a loop after the bytes.
// printerProgram(Emu, { port: 'dragon' | 'coco', bytes, slow }) -> a DragonDOS binary (Session.load runs it)
const hex = (b) => `$${b.toString(16).padStart(2, '0').toUpperCase()}`;
const fcb = (bytes) => {
  let out = '';
  for (let i = 0; i < bytes.length; i += 8) out += `        FCB     ${bytes.slice(i, i + 8).map(hex).join(',')}\n`;
  return out;
};

const PUT = {
  // the byte on the data lines, then the strobe up and down
  dragon: `PUT     STA     $FF02
        LDA     #$02
        STA     $FF20
        CLR     $FF20
        RTS
`,
  // a start bit, 8 data bits from bit 0, two bit times of stop; every bit ~1491 cycles (182 turns of 8 cycles and
  // about 38 cycles of the rest)
  coco: `PUT     PSHS    A,B,X
        STA     SHREG
        CLR     $FF20           ; start bit: space
        BSR     BITW
        LDB     #8
PBIT    LDA     #0
        LSR     SHREG
        BCC     P0
        LDA     #$02            ; mark
P0      STA     $FF20
        BSR     BITW
        DECB
        BNE     PBIT
        LDA     #$02
        STA     $FF20           ; stop bit: mark
        BSR     BITW
        BSR     BITW
        PULS    A,B,X,PC
BITW    LDX     #182
BW      LEAX    -1,X
        BNE     BW
        RTS
`,
};

const INIT = {
  // PIA0 B all outputs (the data lines); PIA1 A: PA1 (the strobe) and the DAC outputs, low
  dragon: `        CLR     $FF03
        LDA     #$FF
        STA     $FF02
        LDA     #$04
        STA     $FF03
        CLR     $FF21
        LDA     #$FE
        STA     $FF20
        LDA     #$04
        STA     $FF21
        CLR     $FF20
`,
  // PIA1 A: PA1 (the RS-232 out) and the DAC outputs; the line at mark, then two bit times of it before the first byte
  coco: `        CLR     $FF21
        LDA     #$FE
        STA     $FF20
        LDA     #$04
        STA     $FF21
        LDA     #$02
        STA     $FF20
        JSR     BITW
        JSR     BITW
`,
};

function printerSource({ port, bytes, slow }) {
  return `* printer test (${port}), generated by tools/printer-program.js
        ORG     $3000
START   ORCC    #$50
        LDS     #$3000
${INIT[port]}        LDY     #TEXT
FIRST   CMPY    #TEXTEND
        BEQ     SLOW
        LDA     ,Y+
        JSR     PUT
        BRA     FIRST
SLOW    ${slow ? 'LDY     #LINEW' : 'BRA     SLOW'}
${slow ? `LW      LDA     ,Y+
        BEQ     NUM
        JSR     PUT
        BRA     LW
NUM     LDA     COUNT
        BSR     PBCD
        LDA     COUNT+1
        BSR     PBCD
        LDA     #$0D
        JSR     PUT
        LDA     COUNT+1
        ADDA    #1
        DAA
        STA     COUNT+1
        LDA     COUNT
        ADCA    #0
        DAA
        STA     COUNT
        LDX     #11000          ; about 0.1 s
DL      LEAX    -1,X
        BNE     DL
        BRA     SLOW
PBCD    PSHS    A
        LSRA
        LSRA
        LSRA
        LSRA
        ADDA    #'0
        JSR     PUT
        PULS    A
        ANDA    #$0F
        ADDA    #'0
        JMP     PUT
LINEW   FCC     /LINE /
        FCB     0
` : ''}${PUT[port]}COUNT   FCB     0,1
SHREG   FCB     0
TEXT
${fcb(bytes)}TEXTEND
        END     START
`;
}

function printerProgram(Emu, opts) {
  const res = Emu.assemble(printerSource(opts), '6809');
  if (!res.ok) throw new Error(`printer program: ${JSON.stringify(res.errors)}`);
  return Emu.toBinary(res, { format: 'dragondos' });
}

