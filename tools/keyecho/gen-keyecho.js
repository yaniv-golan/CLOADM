// keyecho for a machine: { cpu, source } from its profile and keyboard matrix
function keyecho(Emu, profileId) {
  const p = Emu.profiles[profileId], pos = Emu.keyboards[p.keyboard];
  return p.family === 'mc10' ? { cpu: '6803', source: source6803(pos) } : { cpu: '6809', source: source6809(pos) };
}
function keyechoBinary(Emu, profileId) {
  const { cpu, source } = keyecho(Emu, profileId);
  const res = Emu.assemble(source, cpu);
  if (!res.ok) throw new Error(`keyecho ${profileId}: ${JSON.stringify(res.errors)}`);
  return Emu.toBinary(res);
}
// what the screen must hold after typing text (one line, no ENTER): each character's VDG code in normal video,
// a letter in its capital; an upper-case letter typed with Shift is the machine's SHIFTed letter (inverse)
const expectedCodes = (text) => [...text].map((ch) => (/[A-Z]/.test(ch) ? inverse(vdg(ch)) : vdg(ch.toUpperCase())));

// The legends of a keyboard as character -> { key, shift }: the key whose legend the character is, and whether
// that legend is the key's SHIFTed one (the 6847 shows $20-$5F, so the characters are those)
function legends(Emu, layout) {
  const pos = Emu.keyboards[layout], { plain, shifted } = tables(pos), byIndex = {};
  for (const [name, [r, c]] of Object.entries(pos)) byIndex[r * 8 + c] = name;
  const out = {};
  for (let ch = 32; ch < 0x60; ch++) {
    const s = String.fromCharCode(ch), i = plain.indexOf(vdg(s)), j = shifted.indexOf(vdg(s));
    if (i >= 0) out[s] = { key: byIndex[i], shift: false };
    else if (j >= 0) out[s] = { key: byIndex[j], shift: true };
  }
  return out;
}
// every printable character a machine's keyboard can type, in ASCII order from '!' (lower-case letters too)
function printable(Emu, profileId) {
  const want = legends(Emu, Emu.profiles[profileId].keyboard);
  let t = '';
  for (let c = 33; c < 127; c++) { const ch = String.fromCharCode(c); if (want[ch.toUpperCase()] && (c < 0x60 || /[a-z]/.test(ch))) t += ch; }
  return t;
}

module.exports = { keyecho, keyechoBinary, expectedCodes, tables, vdg, inverse, legends, printable };
