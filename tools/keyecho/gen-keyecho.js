// Key-echo firmware, our own, for checking host typing on the screen without a BASIC ROM (AGENTS.md section 1):
// it scans the keyboard matrix as the machines' BASIC does and writes the character each newly pressed key
// stands for to the text screen, so what a person typed can be read back from video RAM. The no-ROM stub cannot
// serve here: its POLCAT reads key codes from the host directly and never sees the matrix.
//
// The decoding is the machines' keyboard legends, written here independently of js/machines/keyboards.js'
// charToKeys (the code under test):
//  * unshifted, a key types its legend: the digits, : ; , - . / @, the letters, SPACE, and UP as ^;
//  * SHIFT on the digit and punctuation keys gives the upper legend of the bit-paired keycaps - 1! 2" 3# 4$ 5%
//    6& 7' 8( 9) :* ;+ ,< -= .> /? (MAME 0.264 PORT_CHAR pairs in src/mame/trs/dragon.cpp dragon_keyboard,
//    coco3.cpp coco3_keyboard and mc10.cpp mc10/alice; the same legends are printed on the keycaps);
//  * SHIFT with DOWN, RIGHT and CLEAR gives [ ] and \ (Color BASIC's keyboard table: KEYIN's shifted
//    control-key codes $5B, $5D, $5C, "Color BASIC Unravelled II"), as on the Dragon, whose BASIC shares it;
//  * anything else SHIFTed - a letter, 0, @, UP - is written in inverse video, the way the CoCo shows a SHIFTed
//    letter (lower case), so a stray SHIFT is visible on the screen;
//  * ENTER starts the next line; other keys (BREAK, LEFT, CTRL ...) write nothing.
// The key positions come from js/machines/keyboards.js' matrices, which tests/input.test.js and the MAME
// comparisons (tools/mame-diff) check against MAME's ports.
const UPPER = { 1: '!', 2: '"', 3: '#', 4: '$', 5: '%', 6: '&', 7: "'", 8: '(', 9: ')', ':': '*', ';': '+', ',': '<', '-': '=', '.': '>', '/': '?' };
const SHIFT_CTRL = { DOWN: '[', RIGHT: ']', CLEAR: '\\' };
const ENTER = 0xFF;
// the VDG's code for an ASCII character in normal video (the 6847's character set: @.._ are $40-$5F, space..?
// are $60-$7F in normal video, and the low six bits alone are inverse video)
const vdg = (ch) => { const c = ch.charCodeAt(0); return c >= 0x40 ? c : c + 0x40; };
const inverse = (code) => code & 0x3F;

// the two 56-byte tables, row * 8 + column -> VDG code (0: nothing), unshifted and SHIFTed
function tables(pos) {
  const plain = new Array(56).fill(0), shifted = new Array(56).fill(0);
  for (const [name, [r, c]] of Object.entries(pos)) {
    const i = r * 8 + c;
    if (name === 'ENTER') { plain[i] = shifted[i] = ENTER; continue; }
    const legend = name === 'SPACE' ? ' ' : name === 'UP' ? '^' : name.length === 1 ? name : null;
    if (legend) plain[i] = vdg(legend);
    if (name === 'SPACE') shifted[i] = vdg(' ');
    else if (UPPER[name]) shifted[i] = vdg(UPPER[name]);
    else if (SHIFT_CTRL[name]) shifted[i] = vdg(SHIFT_CTRL[name]);
    else if (legend) shifted[i] = inverse(vdg(legend));
  }
  return { plain, shifted };
}
const hex = (b) => `$${b.toString(16).padStart(2, '0').toUpperCase()}`;
const fcb = (bytes) => {
  let out = '';
  for (let i = 0; i < bytes.length; i += 8) out += `        FCB     ${bytes.slice(i, i + 8).map(hex).join(',')}\n`;
  return out;
};

// 6809 (Dragon and CoCo): PIA0 port B drives the columns, port A reads the rows; SHIFT is row 6 of column 7
function source6809(pos) {
  const { plain, shifted } = tables(pos);
  return `* keyecho (6809), generated by tools/keyecho/gen-keyecho.js
SCREEN  EQU     $0400
        ORG     $3000
START   ORCC    #$50
        LDS     #$3000
        CLR     $FF03           ; PIA0 B: DDR next
        LDA     #$FF
        STA     $FF02           ; every column an output
        LDA     #$04
        STA     $FF03
        CLR     $FF01           ; PIA0 A: DDR next
        CLR     $FF00           ; every row an input
        LDA     #$04
        STA     $FF01
        LDX     #SCREEN
        LDA     #$60            ; space
CLS     STA     ,X+
        CMPX    #SCREEN+512
        BNE     CLS
        LDX     #SCREEN
        STX     CURSOR
        LDX     #PREV
        LDB     #8
CLRP    CLR     ,X+
        DECB
        BNE     CLRP
MAIN    CLRB
COL     LDX     #STROBE
        LDA     B,X
        STA     $FF02
        LDA     $FF00
        COMA
        ANDA    #$7F            ; bit 7 is the joystick comparator
        CMPB    #7
        BNE     NOSH
        ANDA    #$3F            ; SHIFT is not a key of its own
NOSH    STA     NOW
        LDX     #PREV
        LDA     B,X
        COMA
        ANDA    NOW
        STA     NEW             ; down now and not before
        LDA     NOW
        STA     B,X
        STB     COLN
        CLR     ROWN
RLOOP   LSR     NEW
        BCC     RNEXT
        BSR     KEY
RNEXT   INC     ROWN
        LDA     ROWN
        CMPA    #7
        BNE     RLOOP
        LDB     COLN
        INCB
        CMPB    #8
        BNE     COL
        BRA     MAIN
KEY     LDA     #$7F            ; SHIFT read when the key is found, as BASIC's KEYIN does: column 7 alone,
        STA     $FF02           ; row 6 (the matrix only changes between frames, so the two reads agree)
        LDA     $FF00
        COMA
        ANDA    #$40
        STA     SHIFT
        LDA     ROWN
        LSLA
        LSLA
        LSLA
        ADDA    COLN
        LDX     #PLAIN
        TST     SHIFT
        BEQ     K1
        LDX     #SHIFTED
K1      LDA     A,X
        BEQ     KDONE
        LDX     CURSOR
        CMPA    #$FF
        BNE     KPUT
        TFR     X,D
        ADDD    #32
        ANDB    #$E0
        TFR     D,X
        BRA     KEND
KPUT    STA     ,X+
KEND    CMPX    #SCREEN+512
        BLO     KST
        LDX     #SCREEN
KST     STX     CURSOR
KDONE   RTS
STROBE  FCB     $FE,$FD,$FB,$F7,$EF,$DF,$BF,$7F
CURSOR  FDB     0
SHIFT   FCB     0
NOW     FCB     0
NEW     FCB     0
ROWN    FCB     0
COLN    FCB     0
PREV    RMB     8
PLAIN
${fcb(plain)}SHIFTED
${fcb(shifted)}        END     START
`;
}

