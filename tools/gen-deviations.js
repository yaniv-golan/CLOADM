#!/usr/bin/env node
// Writes the served page /deviations/ ("Known differences from MAME") from docs/verification.md's "Deviations from
// MAME" section: the section's Markdown (paragraphs, bullet lists, `code`, [links](...)) as HTML, between the
// page's markers. The doc is the one place the differences are written; the page is generated from it, never edited.
//
//   node tools/gen-deviations.js           write deviations/index.html
//   node tools/gen-deviations.js --check   exit 1 if the page is out of date (tests/deviations.test.js checks it too)
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const DOC = path.join(ROOT, 'docs', 'verification.md'), PAGE = path.join(ROOT, 'deviations', 'index.html');
const HEADING = '## Deviations from MAME';
const START = '<!-- deviations:start (generated by tools/gen-deviations.js from docs/verification.md) -->', END = '<!-- deviations:end -->';
const DOCS = 'https://github.com/yaniv-golan/cloadm/blob/main/docs/';

// the section's Markdown: from its heading to the next "## " heading
function section(md = fs.readFileSync(DOC, 'utf8')) {
  const a = md.indexOf(`\n${HEADING}\n`);
  if (a < 0) throw new Error(`docs/verification.md: no "${HEADING}" section`);
  const body = md.slice(a + HEADING.length + 2), b = body.search(/^## /m);
  return (b < 0 ? body : body.slice(0, b)).trim();
}
const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// inline Markdown: `code` first (its contents are left alone), then [text](url) (a relative link goes to the docs on
// GitHub, as the site does not serve them), then **strong** and *emphasis*; a " in the text or a link is escaped
function inline(t) {
  return t.split(/(`[^`]*`)/).map((part) => {
    if (/^`[^`]*`$/.test(part)) return `<code>${esc(part.slice(1, -1))}</code>`;
    return esc(part)
      .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (m, text, url) => `<a href="${/^[a-z]+:/i.test(url) ? url : DOCS + url}">${text}</a>`)
      .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
      .replace(/(^|[^*\w])\*([^*\s](?:[^*]*[^*\s])?)\*(?![*\w])/g, '$1<em>$2</em>');
  }).join('');
}
// blocks: a bullet ("* " at the line start, continued by indented lines) or a paragraph (lines up to a blank line)
function toHtml(md) {
  const out = [], lines = md.split('\n');
  let list = null, para = null;
  const flushPara = () => { if (para) { out.push(`    <p>${inline(para.join(' '))}</p>`); para = null; } };
  const flushList = () => { if (list) { out.push('    <ul>', ...list.map((it) => `      <li>${inline(it.join(' '))}</li>`), '    </ul>'); list = null; } };
  for (const raw of lines) {
    const line = raw.trimEnd();
    if (!line.trim()) { flushPara(); continue; }   // a blank line ends a paragraph; a list goes on past it
    const bullet = /^[*-] (.*)$/.exec(line);
    if (bullet) { flushPara(); (list = list || []).push([bullet[1]]); continue; }
    if (list && /^\s+\S/.test(line) && !para) { list[list.length - 1].push(line.trim()); continue; }
    flushList();
    (para = para || []).push(line.trim());
  }
  flushPara(); flushList();
  return out.join('\n');
}
function splice(html, part) {
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error('deviations/index.html: markers not found');
  return html.slice(0, a) + START + '\n' + part + '\n    ' + html.slice(b);
}
const expected = () => splice(fs.readFileSync(PAGE, 'utf8'), toHtml(section()));
module.exports = { section, toHtml, inline, expected, PAGE, START, END };

if (require.main === module) {
  const want = expected();
  if (process.argv.includes('--check')) {
    if (want !== fs.readFileSync(PAGE, 'utf8')) { console.error('deviations/index.html is out of date: run node tools/gen-deviations.js'); process.exitCode = 1; }
  } else { fs.writeFileSync(PAGE, want); console.log('deviations/index.html written'); }
}
