// Rebuild examples/*.bin: node tools/build-examples.js
// It then brings sw.js's offline file list up to date (tools/pwa-files.js), so a new example file does not leave
// tests/pwa.test.js failing until `node tools/pwa-files.js --write` is run by hand.
// Each entry: source, the CPU its assembler plugin is for, whether the source INCLUDEs files from examples/
// (LIZA's shared conversation data and the welcome program's screen data are two), read here and handed to
// the assembler, and any assemble-time flags. Every flag is passed explicitly as 0 or 1: an IF on a symbol
// that was not passed is an assembler error, so a typo cannot build the wrong variant silently.
const fs = require('fs'), path = require('path');
const { syncSw } = require('./pwa-files.js');
const Emu = require('../tests/load.js')();
const EX = path.join(__dirname, '../examples');
const include = (name) => {
  const p = path.join(EX, name);
  return fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
};
for (const { name, cpu, source = null, defines = {} } of [
  { name: 'liza', cpu: '6809' },
  // LIZA for the 6803, one build per machine so its title names the one it runs on (the two titles are the
  // same length, so the builds differ only in the name). SIX09 is 0: this source has no 6809 title.
  { name: 'liza6803-mc10', cpu: '6803', source: 'liza6803', defines: { MC10: 1, ALICE: 0, SIX09: 0 } },
  { name: 'liza6803-alice', cpu: '6803', source: 'liza6803', defines: { MC10: 0, ALICE: 1, SIX09: 0 } },
  // The welcome data file selects the subtitle with one flag per build family, and every welcome build
  // passes ALL THREE: exactly one is 1. An omitted flag would be an assembler error, not a silent default.
  { name: 'welcome', cpu: '6809', defines: { MC10: 0, ALICE: 0, SIX09: 1 } },
  // the shipping 6803 builds, one per machine; HALTCODE 0 leaves out the HALT the program does not
  // have by design (the MAME comparison build is generated by its spec with HALTCODE 1)
  { name: 'welcome6803-mc10', cpu: '6803', source: 'welcome6803', defines: { HALTCODE: 0, MC10: 1, ALICE: 0, SIX09: 0 } },
  { name: 'welcome6803-alice', cpu: '6803', source: 'welcome6803', defines: { HALTCODE: 0, MC10: 0, ALICE: 1, SIX09: 0 } },
  { name: 'chat', cpu: '6809' },
  // the starter game (docs/game-development.md): one binary for the Dragon and the CoCo, on the built-in firmware
  { name: 'starter-game/catch', cpu: '6809' },
]) {
  const file = source || name;
  const res = Emu.assemble(fs.readFileSync(path.join(EX, `${file}.asm`), 'utf8'), cpu, { include, defines });
  // a failed assembly is fatal; `return` is legal here at module top level and leaves the loop
  if (!res.ok) { console.error(res.errors); process.exitCode = 1; return; }
  const bin = Emu.toBinary(res);
  fs.writeFileSync(path.join(EX, `${name}.bin`), bin);
  console.log(`examples/${name}.bin: ${bin.length} bytes (${cpu})`);
}
// Reached only when every build succeeded (a failed one returns above). The examples are served, so sw.js keeps them.
{
  const { changed, count } = syncSw(path.join(__dirname, '..'));
  console.log(changed ? `sw.js: file list updated (${count} files); commit it with the examples` : `sw.js: file list already up to date (${count} files)`);
}
