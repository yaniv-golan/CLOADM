// Generates welcome-load.asm: the MAME comparison image for the 6803 welcome program.
//
// The shipping welcome runs at $5000 in RAM, loaded by the page. MAME cannot inject a .bin into RAM and set
// PC the way the page does, and putting the program in the ROM socket instead would break the "shipping and
// comparison builds differ only at the HALT site" test (the program's addresses are absolute: it ORGs at
// $5000). So this generates a small loader for the ROM socket at $E000 that copies the program from a fixed
// place in the ROM image to $5000 and jumps to it. The ROM image is the loader plus the HALTCODE=1 build,
// byte for byte; both emulators run the same image, and the machine executes the shipped bytes.
//
//   node tools/mame-diff/mc10/gen-welcome.js [mc10|alice] [--back]
//
// --back: before it jumps, the loader sets what the Session sets for a returning visitor:
// GREET = 1 ("WELCOME BACK") and CARRY = "CARRY ON WITH LIZA" (option 5), so the comparison draws that menu.
// Without it both stay 0, the first visit's menu.
//
// spec.js's welcome() calls this, then assembles welcome-load.asm and places the program in the image.
const fs = require('fs'), path = require('path');
const { writeAtomic } = require('../lib/firmware');

const ROOT = path.join(__dirname, '../../..');
const ROM_BASE = 0xE000;             // the MC-10/Alice ROM socket
const LOAD = 0x5000;                 // the welcome program's ORG
const BODY = 0xF000;                 // where the program sits in the ROM image: above the loader, below the vectors

// A plain function ending in `return` on failure, so nothing forces process.exit() (Node 25 deadlocks in it).
function main() {
  const machineId = process.argv[2] && !process.argv[2].startsWith('--') ? process.argv[2] : 'mc10';
  const back = process.argv.includes('--back');
  const Emu = require(path.join(ROOT, 'tests/load.js'))();
  const include = (name) => {
    const p = path.join(ROOT, 'examples', name);
    return fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
  };
  const flags = machineId === 'alice' ? { MC10: 0, ALICE: 1 } : { MC10: 1, ALICE: 0 };
  const asm = Emu.assemble(fs.readFileSync(path.join(ROOT, 'examples/welcome6803.asm'), 'utf8'), '6803',
    { include, defines: Object.assign({ HALTCODE: 1, SIX09: 0 }, flags) });
  if (!asm.ok) { console.error(asm.errors); process.exitCode = 1; return; }
  const image = Emu.toBinary(asm);
  if (image[0] !== 0x55) { console.error('the welcome6803 comparison build is not one contiguous block'); process.exitCode = 1; return; }
  const body = image.subarray(9);      // the program bytes, contiguous from LOAD
  if (LOAD + body.length > 0x10000) { console.error('the program runs past the end of memory'); process.exitCode = 1; return; }

  // The loader. The 6803 has one index register, so the 16-bit destination and the 16-bit count live in the
  // on-chip RAM at $80-$8F. For each byte: take it via X, save X and the byte on the stack, load the
  // destination into X, store, restore X; then step the destination and count down.
  // The program follows as FCB, 16 to a line, so this one generated file holds the whole image (as diag.asm
  // does) and there is no second file to keep in step.
  const fcbs = [];
  for (let i = 0; i < body.length; i += 16) fcbs.push([...body.subarray(i, i + 16)].map((v) => '$' + v.toString(16).toUpperCase().padStart(2, '0')).join(','));
  const fcbLines = fcbs.join('\n        FCB     ');
  // GREET and CARRY as the Session pokes them (js/session.js startWelcome), set after the copy
  const greet = asm.symbols.get('GREET'), carry = asm.symbols.get('CARRY');
  const sets = back ? [[greet, 1], ...[...'CARRY ON WITH LIZA', '\0'].map((c, i) => [carry + i, c.charCodeAt(0)])] : [];
  const setLines = sets.map(([a, v]) => `        LDA     #$${v.toString(16).toUpperCase()}\n        STA     $${a.toString(16).toUpperCase()}`).join('\n');
  const src = `; GENERATED by tools/mame-diff/mc10/gen-welcome.js - do not edit
; The 6803 welcome program's comparison image for one machine. This loader sits in the ROM socket at $E000;
; the HALTCODE=1 build of examples/welcome6803.asm (assembled with that machine's flag) is stored at
; $${BODY.toString(16)} in the same image. The loader copies it to $${LOAD.toString(16)} and jumps there, so
; MAME runs the shipped program's own bytes.
BODY    EQU     $${BODY.toString(16)}
DEST    EQU     $${LOAD.toString(16)}
LEN     EQU     $${body.length.toString(16)}     ; ${body.length} bytes
COUNT   EQU     $80             ; 16-bit bytes left to copy
DPTR    EQU     $82             ; 16-bit destination cursor

        ORG     $${ROM_BASE.toString(16)}
RESET   SEI
        LDS     #$8EFF
        LDD     #LEN
        STD     COUNT
        LDD     #DEST
        STD     DPTR
        LDX     #BODY
CPLOOP  LDA     0,X             ; the byte
        PSHX                    ; keep the source pointer, then the byte on top of it
        PSHA
        LDX     DPTR
        PULA                    ; the byte back (A is on top)
        STA     0,X
        PULX                    ; the source pointer back
        INX
        INC     DPTR+1          ; step the destination (16-bit, no carry test: the count bounds it)
        BNE     CNT
        INC     DPTR
CNT     LDD     COUNT           ; one byte done: count it down with a 16-bit subtract
        SUBD    #1
        STD     COUNT
        BNE     CPLOOP
${back ? `; a returning visitor's menu: GREET = 1, CARRY = "CARRY ON WITH LIZA" (--back)\n${setLines}\n` : ''}        JMP     DEST
; the HALTCODE=1 build of examples/welcome6803.asm, byte for byte (the loader copies it to DEST)
        ORG     $${BODY.toString(16)}
PROGRAM FCB     ${fcbLines}
        ORG     $FFFE
        FDB     RESET
        END     RESET
`;
  const out = `welcome-load-${machineId}${back ? '-back' : ''}.asm`;
  writeAtomic(path.join(__dirname, out), src);
  console.log(`${out}: loader, program ${body.length} bytes at $${BODY.toString(16)} -> $${LOAD.toString(16)}`);
}

main();
