#!/usr/bin/env node
// Generates raster.asm for the MC-10: mid-line latch writes swept across every beam position
// Our own firmware, installed in place of mc10.rom.
//
// The MC-10's CPU cannot see the raster (the VDG's sync outputs are not wired to it), so the firmware
// is cycle-exact instead: one pass of its main loop takes exactly one field (262 lines of 57 cycles =
// 14934 cycles), so the writes land on the same beam positions in every field. Each pass reads one
// record of a table - the case, its field number, the latch value restored at the start of every swept
// line (A), the value written part-way along it (B) and a lead-in marker - so every pass runs the same
// instructions whatever the case. The loop's length is measured on our emulator, whose 6803 timing the
// lockstep comparison with MAME checks instruction by instruction, and padded to exactly one field.
//
// Per field:
//   SWEEP  57-cycle line blocks: write A, wait d cycles, write B, wait the rest; d grows by one cycle per
//          line, so B lands one byte position later on each line (A lands where the field's phase puts it);
//   ALT    57-cycle line blocks writing B and A alternately, d cycles into the block, d growing per line.
// Each case first shows LEAD_IN fields with B = A (a plain picture) whose first display byte alternates,
// so MAME redraws both of its screen bitmaps with complete lines before the swept fields (see
// MC6847.endLine), and the harness can check that the swept fields differ from the plain one.
const fs = require('fs'), path = require('path');
const { writeAtomic } = require('../lib/firmware');

const FIELD_CYCLES = 262 * 57;
const LEAD_IN = 3, SWEPT = 6;            // fields per case
const RECORD = 5;                        // bytes per table record
// latch bits: 2 GM2 and INT/EXT, 3 GM1, 4 GM0, 5 A/G, 6 CSS, 7 sound (not video)
const cases = [
  ['text -> CG1', 0x00, 0x20],
  ['CG1 -> text', 0x20, 0x00],
  ['text CSS0 -> CSS1', 0x00, 0x40],
  ['text -> external characters (INT/EXT)', 0x00, 0x04],
  ['text -> RG1', 0x00, 0x30],
  ['RG3 -> CG6', 0x34, 0x2C],
  ['CG6 -> RG3', 0x2C, 0x34],
  ['CG2 CSS0 -> CSS1', 0x28, 0x68],
  ['CG3 -> RG2', 0x24, 0x38],
  ['sound bit only (no effect)', 0x00, 0x80, 'no effect'],
];

function generate({ align, prePad, padCount, padFine }) {
  const L = [];
  const emit = (s) => L.push(s);
  const delay = (n) => {           // exactly n cycles (n = 0 or n >= 2): NOP 2, BRN 3
    if (n === 1 || n < 0) throw new Error(`cannot delay ${n} cycles`);
    if (n % 2) { emit('        BRN     *'); n -= 3; }
    for (; n > 0; n -= 2) emit('        NOP');
  };
  emit(`; GENERATED by gen-raster.js - do not edit. Mid-line latch writes swept across the beam (MC-10).
PHASE   EQU     $8F00
FIELDN  EQU     $8F01
REC     EQU     $8F02
LATCH   EQU     $BFFF
        ORG     $E000
RESET   SEI
        LDS     #$8EFF
        LDAA    #$FF
        STAA    $00             ; DDR1: keyboard column strobes are outputs, none strobed
        STAA    $02
        ; display data over $4000-$5FFF: (low * 7) xor (high * 37) of the offset, so every row,
        ; column and page differs and every character, semigraphics block and pixel pattern occurs
        LDX     #$4000
GX      PSHX
        TSX
        LDAA    1,X             ; low byte of the address
        LDAB    #7
        MUL
        STAB    $8F10
        LDAA    0,X             ; high byte (offset from $4000)
        SUBA    #$40
        LDAB    #37
        MUL
        EORB    $8F10
        PULX
        STAB    0,X
        INX
        CPX     #$6000
        BNE     GX
        LDX     #TABLE
        STX     REC
        CLR     LATCH
        LDX     #${align}       ; once: sets the phase of every pass, so the sweep falls in the active area
ALIGN   DEX
        BNE     ALIGN
; ---- one pass = one field (${FIELD_CYCLES} cycles)
FIELD   LDX     REC
        LDAA    0,X
        CMPA    #$FF
        BNE     FGO
        JMP     DONE
FGO     STAA    PHASE
        LDAA    1,X
        STAA    FIELDN
        LDAA    4,X
        STAA    $4000           ; first display byte: alternates in the lead-in fields
        LDAA    2,X
        LDAB    3,X
        LDX     #${prePad}       ; to the first swept line
PRE     DEX
        BNE     PRE`);
  emit('; SWEEP: write A, then B d cycles later; d grows by one cycle per line');
  const ds = [];
  for (let d = 0; d <= 49; d++) if (d !== 1 && d !== 48) ds.push(d);
  for (const d of ds) {
    emit(`        STAA    LATCH           ; d = ${d}`);
    delay(d);
    emit('        STAB    LATCH');
    delay(57 - 8 - d);
  }
  emit('        STAA    LATCH');
  delay(57 - 4);
  emit('; ALT: lines write B and A alternately, d cycles into their block');
  for (let d = 0, k = 0; d <= 53; d++) {
    if (d === 1 || d === 52) continue;
    delay(d);
    emit(k % 2 ? '        STAA    LATCH' : '        STAB    LATCH');
    delay(57 - 4 - d);
    k++;
  }
  emit(`        STAA    LATCH           ; leave the field in state A
        LDX     REC
        LDAB    #${RECORD}
        ABX
        STX     REC
        LDX     #${padCount}       ; pad the pass to exactly one field
PAD     DEX
        BNE     PAD`);
  delay(padFine);
  emit(`        JMP     FIELD
DONE    LDAA    #$FF
        STAA    PHASE
HALT    BRA     HALT
TABLE`);
  cases.forEach(([, a, b], i) => {
    for (let f = 0; f < LEAD_IN + SWEPT; f++) {
      const n = LEAD_IN + SWEPT - f, lead = f < LEAD_IN;
      emit(`        FCB     ${i + 1},${n},$${a.toString(16)},$${(lead ? a : b).toString(16)},${lead ? f & 1 : 1}`);
    }
  });
  emit(`        FCB     $FF
        ORG     $FFFE
        FDB     RESET
        END     RESET`);
  return L.join('\n') + '\n';
}

// measure, on our emulator, the cycles of one pass and the line its first sweep write lands on
function measure(src) {
  const Emu = require(path.join(__dirname, '../../../tests/load.js'))();
  const asm = Emu.assemble(src, '6803');
  if (!asm.ok) throw new Error(asm.errors.map((e) => `line ${e.line}: ${e.message}`).join('; '));
  const rom = new Uint8Array(0x2000).fill(0x01);
  for (const s of asm.segments) if (s.addr >= 0xE000) rom.set(s.data.subarray(0, 0x10000 - s.addr), s.addr - 0xE000);
  const m = Emu.createMachine('mc10', { mameCompat: true });
  m.setRoms({ basic: rom });
  m.reset(true);
  const field = asm.symbols.get('FIELD'), starts = [];
  m.cpu.trace = (c) => { if (c.pc === field) starts.push(c.totalCycles); };
  let firstLine = null;
  const ow = m.write.bind(m);
  m.write = function (a, v) {
    if (a === 0xBFFF && firstLine === null && starts.length === 3) firstLine = this.beam ? this.beam.body : -1;
    return ow(a, v);
  };
  for (let f = 0; f < 300 && starts.length < 4; f++) m.runFrame();
  return { pass: starts[3] - starts[2], firstLine };
}

// solve the padding and alignment on our emulator, then write raster.asm (run as a script, or from
// spec.raster before a MAME comparison)
function write() {
  const FIRST_ROW = 12;     // put the first swept line about this far into the active area
  // 1. pad one pass to exactly a field (the delay loops cost 6 cycles per count)
  let p = { align: 1, prePad: 1, padCount: 1, padFine: 0 };
  let r = measure(generate(p));
  const extra = FIELD_CYCLES - r.pass;
  if (extra < 0) throw new Error(`one pass takes ${r.pass} cycles, more than a field`);
  p.padFine = extra % 6 === 1 ? 7 : extra % 6;
  p.padCount = 1 + (extra - p.padFine) / 6;
  r = measure(generate(p));
  // 2. a one-time delay before the loop moves the sweep to the active area
  p.align = 1 + Math.round(((FIRST_ROW - r.firstLine + 262) % 262) * 57 / 6);
  const src = generate(p);
  r = measure(src);
  if (r.pass !== FIELD_CYCLES) throw new Error(`one pass takes ${r.pass} cycles, not ${FIELD_CYCLES}`);
  writeAtomic(path.join(__dirname, 'raster.asm'), src);
  if (require.main === module) console.log(`raster.asm: one pass = ${r.pass} cycles, first swept line at active row ${r.firstLine}`);
}
if (require.main === module) write();
module.exports = { cases: cases.map(([name, , , effect], i) => ({ name, phase: i + 1, noEffect: effect === 'no effect' })), FIELDS: LEAD_IN + SWEPT, write };
