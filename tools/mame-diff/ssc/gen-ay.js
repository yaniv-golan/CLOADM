// The Speech/Sound Pak's AY-3-8913 audio case: our own firmware for both CPUs, built from source text here.
//
// THE PIC PROGRAM (TMS7040) plays every step below from its own reset, with interrupts off, and then idles. It
// never waits for the 6809: the comparison is a sample-by-sample one, and a program that waits on the CoCo's
// commands puts the 6809/PIC handshake into the sound. Measured on MAME 0.264 with ssc-tone.asm (which plays its
// sequence once per command): the writes inside one command are spaced exactly as here, but each command starts
// 10-20 us earlier or later than ours, as MAME interleaves its two CPUs on its scheduler (the overlap
// verification.md describes for the INT3 case), and over the run the offset grew past 200 us. Starting from the
// PIC's reset leaves one clock: both emulators reset the card at machine time 0.
//
// THE 6809 PROGRAM only opens the CoCo's sound mux for the cartridge (ssc.asm's MUXON, the condition MAME's
// coco.cpp:555 tests) and stops in a loop; it never touches the Pak.
//
// What the steps cover, in order (js/chips/ay8910.js's register map):
//   A. fixed levels, every tone and noise path off (mixer $3F), so each channel outputs its volume: channel A
//      0-15 alone; B 0-15 with A at 15; C 0-15 with A at 7 and B at 3; all three equal, 0-15. These are the
//      single-output network's levels and its cross terms (aySingleLevel).
//   B. the envelope, mixer $3F, period 32: all 16 shapes on channel A; then on A and C with B fixed at 8 (mixed
//      envelope bits); then on all three; then on A with its tone path on (an envelope channel whose gate is
//      closed half the time still counts as driving).
//   C. tones: periods 0 (taken as 1), 1 and $FFF; then 140, 93 and 50; three volumes.
//   D. noise: periods 0, 1, 16 and 31, alone on all three channels and mixed with tones.
//   E. a write to a deselected chip (address with a non-zero upper nibble), which must change nothing.
//   F. every volume 0 and the mixer off: idle.
// The hold after each step is in units of DELAY (256 passes of a 9/11-cycle DJNZ, about 2.8k card cycles, 3 ms).
const { loadEmu, romImage } = require('../lib/firmware.js');

// [register, value] writes, then a hold
function steps() {
  const s = [];
  const at = (writes, hold) => s.push({ writes, hold });
  at([[7, 0x3F], [8, 0], [9, 0], [10, 0]], 4);
  for (let v = 0; v < 16; v++) at([[8, v]], 2);                           // A alone
  at([[8, 15]], 1);
  for (let v = 0; v < 16; v++) at([[9, v]], 2);                           // B against A = 15
  at([[8, 7], [9, 3]], 1);
  for (let v = 0; v < 16; v++) at([[10, v]], 2);                          // C against A = 7, B = 3
  for (let v = 0; v < 16; v++) at([[8, v], [9, v], [10, v]], 2);         // all three equal
  // B. envelope
  at([[8, 0], [9, 0], [10, 0], [11, 32], [12, 0]], 1);
  for (let shape = 0; shape < 16; shape++) at([[8, 0x10], [13, shape]], 8);
  at([[9, 8], [10, 0x10], [13, 0x0E]], 10);                              // A and C on the envelope, B fixed
  at([[9, 0x10], [13, 0x0A]], 10);                                       // all three
  at([[9, 0], [10, 0], [0, 40], [1, 0], [7, 0x3E], [13, 0x0C]], 10);     // A: envelope with its tone gate
  // C. tones
  at([[7, 0x38], [0, 0], [1, 0], [2, 1], [3, 0], [4, 0xFF], [5, 0x0F], [8, 15], [9, 10], [10, 5]], 20);
  at([[0, 140], [2, 93], [4, 50], [5, 0]], 20);
  at([[1, 0x01], [3, 0x02]], 10);                                        // coarse periods
  // D. noise
  at([[7, 0x07], [6, 0], [8, 15], [9, 8], [10, 4]], 10);
  at([[6, 1]], 10);
  at([[6, 16]], 10);
  at([[6, 31]], 10);
  at([[7, 0x30], [6, 5]], 10);                                           // tone and noise on all three
  at([[7, 0x2A], [6, 2]], 10);                                           // mixed paths per channel
  // E. a deselected write: address $18 (upper nibble set), then data 0, must leave volume A at 15
  s.push({ deselected: [0x18, 0x00], hold: 10 });
  // F. idle
  at([[8, 0], [9, 0], [10, 0], [7, 0x3F]], 4);
  return s;
}

const hex = (v) => `$${v.toString(16).toUpperCase().padStart(2, '0')}`;

function picSource() {
  const lines = [
    '* generated by tools/mame-diff/ssc/gen-ay.js: the AY audio case, played from the PIC\'s reset',
    '        ORG     $F000',
    'RESET   DINT',
    '        MOVP    %$00,P0 ; IOCNT0: no interrupt enabled',
    '        MOVP    %$FF,P9 ; port C: outputs (the control bus)',
    '        MOVP    %$FF,P11 ; port D: outputs (the data bus)',
    '        MOVP    %$40,P8 ; port C: AY deselected, ALD low, busy low',
    '        MOVP    %$00,P10',
  ];
  for (const st of steps()) {
    if (st.deselected) {
      const [addr, value] = st.deselected;
      lines.push(`        MOVP    %${hex(addr)},P10 ; address ${hex(addr)}: deselects the AY`,
        '        MOVP    %$09,P8',
        `        MOVP    %${hex(value)},P10 ; data, ignored`,
        '        MOVP    %$08,P8',
        '        MOVP    %$40,P8');
    } else {
      for (const [r, v] of st.writes) lines.push(`        MOV     %${hex(r)},A`, `        MOV     %${hex(v)},B`, '        CALL    @AYREG');
    }
    lines.push(`        MOV     %${hex(st.hold)},R20`, '        CALL    @DELAY');
  }
  lines.push(
    'IDLE    JMP     IDLE',
    '* one AY register write: A = register, B = value (port D carries both, port C strobes BDIR/BC1)',
    'AYREG   MOVP    A,P10',
    '        MOVP    %$09,P8 ; BDIR|BC1: latch the address',
    '        MOVP    B,P10',
    '        MOVP    %$08,P8 ; BDIR: write the data',
    '        MOVP    %$40,P8 ; deselect',
    '        RETS',
    '* hold for R20 units of 256 inner passes. Not R2-R3: the stack pointer resets to 1, so CALL pushes there',
    'DELAY   MOV     %$00,R0',
    'DLOOP   DJNZ    R0,DLOOP',
    '        DJNZ    R20,DLOOP',
    '        RETS',
    '        ORG     $FFFE',
    '        FDB     RESET',
    '        END     RESET');
  return lines.join('\n') + '\n';
}

// the 6809 side: open the mux (ssc.asm's MUXON) and stop
const HOST_SOURCE = `* generated by tools/mame-diff/ssc/gen-ay.js: opens the CoCo's sound mux for the cartridge, then stops
        ORG     $A000
RESET   ORCC    #$50
        LDS     #$7F00
        LDA     #$30
        STA     $FF01           ; PIA0 CRA: CA2 low  -> SOUNDMUX_SEL1 clear
        LDA     #$38
        STA     $FF03           ; PIA0 CRB: CB2 high -> SOUNDMUX_SEL2
        STA     $FF23           ; PIA1 CRB: CB2 high -> SOUNDMUX_ENABLE
HALT    BRA     HALT
        ORG     $BFF2
        FDB     IRQH,IRQH,IRQH,IRQH,IRQH,IRQH,RESET
IRQH    RTI
        END     RESET
`;

function assemble(src, cpu, what) {
  const res = loadEmu().assemble(src, cpu);
  if (!res.ok) throw new Error(`${what}: ${res.errors.map((e) => `line ${e.line}: ${e.message}`).join('; ')}`);
  return res;
}
// the PIC's 4 KB internal ROM image ($F000-$FFFF)
function ayPic() { return romImage(assemble(picSource(), '7000', 'gen-ay PIC'), 0xF000, 0x1000, 0xFF); }
// the 6809 program, assembled; romImage it into each of a profile's sockets
function ayHost() { return assemble(HOST_SOURCE, '6809', 'gen-ay host'); }

module.exports = { steps, picSource, ayPic, ayHost, HOST_SOURCE };
