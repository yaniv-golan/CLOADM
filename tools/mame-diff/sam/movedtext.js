#!/usr/bin/env node
// The moved text page (tools/mame-diff/sam, written for CLOADM): firmware that prints known text on three VDG text
// pages, then moves the display between them through the SAM's display offset (F6-F0, $FFC6-$FFD3), then turns on
// INT/EXT (semigraphics-6 / external characters) and a graphics mode over the last page. The screen-text readers
// (js/claude/readtools.js: screen_text, Session.screenText, the screen's text alternative, the welcome menu's taps,
// the ROM self-test's screen) must read the page the SAM shows, and read text only in the alphanumeric /
// semigraphics-4 mode.
//
//   node tools/mame-diff/sam/movedtext.js --write          writes movedtext.asm from PAGES (tests/moved-text-page.test.js
//                                                          checks the committed file is current)
//   node tools/mame-diff/run.js <profile> --video --movedtext   every pixel of phases 1-4 against MAME (run-movedtext.js)
//
// Phases (the phase number at PHASE, $7000, read by both emulators' capture scripts), each held 20 fields:
//   1  F = 2,  $0400 (BASIC's page), text          the default page: DEFAULT text
//   2  F = 7,  $0E00, text                         the page moved: MOVED_E00 text
//   3  F = 14, $1C00, text                         moved again: MOVED_1C00 text
//   4  F = 14, $FF22 = $10 (INT/EXT high)          semigraphics-6 / external characters: the readers decline
//   5  F = 14, $FF22 = $F0 (RG6, A/G high)         graphics: the readers decline (not compared with MAME: the
//                                                  redraw toggle below would show in a graphics mode)
// then HALT, in phase 5.
//
// Every page's last cell (row 15, column 31) is the redraw toggle, flipped between $80 and $C0 every field: both are
// semigraphics blocks with no element lit, drawn black in SG4 and SG6 alike, so the picture never changes but every
// field fetches new bytes and MAME redraws its screen bitmaps (as sam/samv.asm does with $0000). The readers count
// that cell as one semigraphics block.
const fs = require('fs'), path = require('path');

const PHASE = 0x7000;
// Each page: its address, the SAM's F for it, and its rows as [row, column, text]; `blocks` are cells holding
// semigraphics-4 bytes, `codes` cells holding raw VDG codes (every code $00-$7F, so every character is shown).
const PAGES = [
  { name: 'DEFAULT', at: 0x0400, f: 2, rows: [
    [0, 0, 'DEFAULT PAGE $0400 (F = 2)'],
    [2, 0, 'BASIC PRINTS HERE AT POWER-ON.'],
    [15, 0, 'LAST ROW OF $0400'],
  ] },
  { name: 'MOVED_E00', at: 0x0E00, f: 7, rows: [
    [0, 0, 'MOVED TO $0E00 (F = 7)'],
    [1, 4, 'THE SAM SHOWS THIS PAGE NOW'],
    [7, 0, 'ROWS 4 AND 5: EVERY VDG CODE'],
    [9, 2, 'ROW 9 HAS BLOCKS AT 28-30:'],
    [15, 0, 'LAST ROW OF $0E00'],
  ], codes: [[4, 0, 0x00, 64], [5, 0, 0x40, 64]].map(([row, col, from, n]) => [row, col, Array.from({ length: n }, (_, i) => from + i)]),
  blocks: [[9, 28, [0x8F, 0x9A, 0xF5]]] },
  { name: 'MOVED_1C00', at: 0x1C00, f: 14, rows: [
    [0, 0, 'MOVED AGAIN, TO $1C00 (F = 14)'],
    [3, 0, '0123456789 !"#$%&\'()*+,-./:;<=>?'],
    [8, 10, 'MIDDLE OF $1C00'],
    [15, 0, 'LAST ROW OF $1C00'],
  ] },
];
const TOGGLE = 15 * 32 + 31;   // each page's redraw toggle cell

// A VDG code for an ASCII character, as BASIC stores normal text: $40-$5F for @A-Z[\]^_, $60-$7F for space to ?.
// (Bit 6 is INV on the Dragon and CoCo; this is the code the firmware writes, not how the test reads it.)
function code(ch) {
  const c = ch.charCodeAt(0);
  if (c >= 0x40 && c <= 0x5F) return c;
  if (c >= 0x20 && c <= 0x3F) return c + 0x40;
  throw new Error(`no VDG code for ${JSON.stringify(ch)}`);
}
// a page's 512 bytes: spaces ($60), then the rows, codes and blocks, the toggle cell $80
function pageBytes(page) {
  const b = new Array(512).fill(0x60);
  for (const [row, col, text] of page.rows) Array.from(text).forEach((ch, i) => { b[row * 32 + col + i] = code(ch); });
  for (const [row, col, list] of page.codes || []) list.forEach((v, i) => { b[row * 32 + col + i] = v; });
  for (const [row, col, list] of page.blocks || []) list.forEach((v, i) => { b[row * 32 + col + i] = v; });
  b[TOGGLE] = 0x80;
  return b;
}

const hx = (v, w = 2) => '$' + v.toString(16).toUpperCase().padStart(w, '0');
function source() {
  const L = [], e = (s) => L.push(s);
  e('; The moved text page (tools/mame-diff/sam, written for CLOADM). GENERATED by movedtext.js --write: edit that file.');
  e(';');
  e('; Three text pages ($0400, $0E00, $1C00) of known text, shown in turn through the SAM\'s display offset, then');
  e('; INT/EXT high and a graphics mode over the last. See movedtext.js for the phases and what each one proves.');
  e(`PHASE   EQU     ${hx(PHASE, 4)}           ; the phase number, read by both emulators' capture scripts`);
  e('        ORG     $8000');
  e('RESET   ORCC    #$50');
  e('        STA     $FFDD           ; SAM M1 = 1 (M1/M0 = 10): 64K RAM');
  e('        LDS     #$7F00');
  e('        CLRA');
  e('        TFR     A,DP');
  e('        ; PIA0 B: outputs (keyboard strobes idle high); PIA1 B: the VDG\'s inputs, text mode, CSS 0');
  for (const l of ['CLR     $FF03', 'LDA     #$FF', 'STA     $FF02', 'LDA     #$34', 'STA     $FF03',
    'CLR     $FF23', 'LDA     #$FF', 'STA     $FF22', 'LDA     #$34', 'STA     $FF23', 'CLR     $FF22']) e(`        ${l}`);
  e('        CLR     PHASE');
  e('        ; the three pages, 512 bytes each, copied from the tables below');
  PAGES.forEach((p, k) => {
    e(`        LDX     #${hx(p.at, 4)}`); e(`        LDU     #PG${k}`);
    e(`CP${k}     LDD     ,U++`); e('        STD     ,X++'); e(`        CMPX    #${hx(p.at + 512, 4)}`); e(`        BLO     CP${k}`);
  });
  // F6-F0: bit k set at $FFC7 + 2k, cleared at $FFC6 + 2k
  const setF = (f) => { for (let k = 0; k < 7; k++) e(`        STA     ${hx(0xFFC6 + 2 * k + ((f >> k) & 1), 4)}`); };
  PAGES.forEach((p, k) => {
    e(`        ; ---- phase ${k + 1}: F = ${p.f}, the page at ${hx(p.at, 4)} ----`);
    setF(p.f);
    e('        INC     PHASE'); e(`        LDX     #${hx(p.at + TOGGLE, 4)}`); e('        JSR     HOLD');
  });
  const last = PAGES[PAGES.length - 1];
  e('        ; ---- phase 4: INT/EXT high (PIA1 PB4): semigraphics-6 and the external-character input ----');
  e('        LDA     #$10'); e('        STA     $FF22');
  e('        INC     PHASE'); e(`        LDX     #${hx(last.at + TOGGLE, 4)}`); e('        JSR     HOLD');
  e('        ; ---- phase 5: A/G high, RG6 (GM2-0 = 111): a graphics mode over the same page ----');
  e('        LDA     #$F0'); e('        STA     $FF22');
  e('        INC     PHASE');
  e('HALT    BRA     HALT');
  e('');
  e('; hold for 20 fields, flipping the toggle cell at X between $80 and $C0 each field (see movedtext.js)');
  e('HOLD    LDB     #20');
  e('HOLD1   LDA     $FF02');
  e('HWFS    LDA     $FF03           ; wait for FS to fall (end of the active area)');
  e('        BPL     HWFS');
  e('        LDA     ,X              ; flip the toggle');
  e('        EORA    #$40');
  e('        STA     ,X');
  e('        LDA     $FF02');
  e('HWFR    LDA     $FF03           ; and rise again');
  e('        BMI     HWFR');
  e('        DECB');
  e('        BNE     HOLD1');
  e('        RTS');
  e('');
  PAGES.forEach((p, k) => {
    const b = pageBytes(p);
    for (let i = 0; i < 512; i += 16) e(`${(i ? '' : `PG${k}`).padEnd(8)}FCB     ${b.slice(i, i + 16).map((v) => hx(v)).join(',')}`);
  });
  e('');
  e('        ORG     $BFF2');
  e('        FDB     HALT,HALT,HALT,HALT,HALT,HALT,HALT');
  e('        ORG     $BFFE');
  e('        FDB     RESET');
  e('        END     RESET');
  return L.join('\n') + '\n';
}

const ASM = path.join(__dirname, 'movedtext.asm');
module.exports = { PAGES, PHASE, TOGGLE, source, ASM };

if (require.main === module && process.argv.includes('--write')) {
  fs.writeFileSync(ASM, source());
  console.log(`wrote ${path.relative(process.cwd(), ASM)}`);
}
