#!/usr/bin/env node
// Generates raster.asm for the CoCo 3: video register writes swept across every beam position.
// Our own firmware, installed in place of coco3.rom. The structure is the SAM family's
// (tools/mame-diff/sam/gen-raster.js): HS on PIA0 CA1 with SYNC, each case shows lead-in fields in its
// starting state and then fields in which a register is written part-way along many lines, one CPU cycle
// later on each line (SWEEP), or on alternate lines (ALT).
//
// The GIME (in MAME and here) records a line when it ends, with the registers in force then: a write part
// way along a line changes the whole of that line, or none of it if the line has already ended. So these
// fields test which line each write lands in, at every cycle of the line, for every kind of register. Only
// graphics modes are used: the text modes use our own font, which differs from MAME's by design.
const fs = require('fs'), path = require('path');
const { writeAtomic } = require('../lib/firmware');

const HS_SKIP = 50;        // HS edges after FS falls before the first swept line
const GAP = 6;             // HS edges between the two patterns
const FIELDS = 9;          // fields per case: STATIC plain fields, then the swept ones
const STATIC = 3;

// Cases: name, starting state { ff90, ff98, ff99, ff9a, ff9f, ff22, samV }, and the two writes:
// [address, value] restoring A and [address, value] setting B. 'no effect': the GIME uses that register
// from the start of a field only (MAME gime.cpp: the video position, the geometry and the COCO bit are
// taken up at new_frame), so writes part-way through a field must not change it - checked both ways.
const G16 = { ff90: 0x00, ff98: 0x80, ff99: 0x1E, ff9a: 0x2A, ff9f: 0x00, ff22: 0x00, samV: 0 };   // 320x192x16
const cases = [
  ['palette entry 1 (320x192x16)', G16, [0xFFB1, 0x08], [0xFFB1, 0x36]],
  // the active area fills the picture's width, so the border shows only above and below it: this case's
  // sweep starts at the top border (skip: HS edges after FS falls)
  ['border colour (320x192x16)', Object.assign({}, G16, { skip: 12 }), [0xFF9A, 0x2A], [0xFF9A, 0x05]],
  ['lines per row 1 -> 2 (320x192x16)', G16, [0xFF98, 0x80], [0xFF98, 0x81], 'no effect'],
  ['resolution 320x16 -> 320x4 ($FF99)', G16, [0xFF99, 0x1E], [0xFF99, 0x15]],
  ['horizontal offset 0 -> 4 ($FF9F)', G16, [0xFF9F, 0x00], [0xFF9F, 0x04]],
  ['vertical offset $70000 -> $70800 ($FF9E)', G16, [0xFF9E, 0x00], [0xFF9E, 0x01], 'no effect'],
  ['GIME graphics -> compatibility CG2 ($FF90 COCO)', Object.assign({}, G16, { ff22: 0xA0, samV: 2 }), [0xFF90, 0x00], [0xFF90, 0x80], 'no effect'],
  ['compatibility CG2 CSS0 -> CSS1 ($FF22)', Object.assign({}, G16, { ff90: 0x80, ff22: 0xA0, samV: 2 }), [0xFF22, 0xA0], [0xFF22, 0xA8]],
];
const PALETTE = [3, 8, 13, 18, 23, 28, 33, 38, 43, 48, 53, 58, 63, 4, 9, 14];

const L = [];
const emit = (s) => L.push(s);
// a delay of exactly n cycles (n = 0 or n >= 2): NOP is 2 cycles, BRN 3
function delay(n) {
  if (n === 1 || n < 0) throw new Error(`cannot delay ${n} cycles`);
  if (n % 2) { emit('        BRN     *'); n -= 3; }
  for (; n > 0; n -= 2) emit('        NOP');
}

emit(`; GENERATED by gen-raster.js - do not edit. Video register writes swept across the beam (CoCo 3).
PHASE   EQU     $7F00
FIELDN  EQU     $7F01
SKIPN   EQU     $7F02
        ORG     $8000
RESET   ORCC    #$50            ; IRQ and FIRQ masked: SYNC resumes without taking the interrupt
        LDS     #$7FF0
        ; display data over $0000-$1FFF (physical $70000, where the vertical offset $E000 points): (low * 7)
        ; xor (high * 37), so every row, column and page differs and every pixel pattern occurs
        LDX     #$0000
GX      TFR     X,D
        PSHS    A
        LDA     #7
        MUL
        PSHS    B
        LDA     1,S
        LDB     #37
        MUL
        EORB    ,S+
        LEAS    1,S
        STB     ,X+
        CMPX    #$2000
        BLO     GX
        LDA     #$FF
        TFR     A,DP
        SETDP   $FF
        ; PIA0: CA1 = HS with its interrupt enabled (falling edge), CB1 = FS flag only. Port B
        ; (the keyboard column strobes) is set to outputs, all high, as the BASIC ROMs do, so
        ; reading it to clear the FS flag returns the output latch in both emulators; port A
        ; stays inputs with no column strobed
        CLR     <$01
        CLR     <$03
        CLR     <$00
        LDA     #$FF
        STA     <$02
        LDA     #$34
        STA     <$03
        LDA     #$FF
        STA     <$02
        LDA     #$35
        STA     <$01
        LDA     #$34
        STA     <$03
        ; PIA1 PB: outputs (the VDG mode bits, used in the compatibility modes)
        CLR     <$23
        LDA     #$FF
        STA     <$22
        LDA     #$34
        STA     <$23
        ; the display starts at physical $70000 (CPU $0000 with the MMU off); the palette
        LDA     #$E0
        STA     <$9D
        CLR     <$9E
        LDX     #PAL
        LDU     #$FFB0
PL      LDA     ,X+
        STA     ,U+
        CMPU    #$FFC0
        BNE     PL
`);

// SAM register writes for a 3-bit V or 7-bit F value (even address clears, odd sets)
const samBits = (base, bits, value) => {
  for (let i = 0; i < bits; i++) emit(`        STA     <$${(base + i * 2 + ((value >> i) & 1)).toString(16).toUpperCase()}`);
};

cases.forEach(([name, st, [ra, rv], [sa, sv]], i) => {
  const ph = i + 1;
  emit(`; ---- case ${ph}: ${name}`);
  emit(`        LDA     #${ph}`);
  emit('        STA     PHASE');
  emit(`        LDA     #${FIELDS}`);
  emit('        STA     FIELDN');
  emit(`C${ph}F    LDA     <$03            ; wait for FS to fall (end of the active area)`);
  emit(`        BPL     C${ph}F`);
  emit('        LDA     <$02');
  // the field's starting state, set in the bottom border
  for (const [reg, val] of [[0x90, st.ff90], [0x98, st.ff98], [0x99, st.ff99], [0x9A, st.ff9a], [0x9F, st.ff9f], [0x9E, 0], [0x22, st.ff22]]) {
    emit(`        LDA     #$${val.toString(16).toUpperCase()}`);
    emit(`        STA     <$${reg.toString(16).toUpperCase()}`);
  }
  emit(`        LDA     #${PALETTE[1]}`);
  emit('        STA     <$B1');
  emit(`        LDX     #${st.skip || HS_SKIP}`);
  emit('        STX     SKIPN');
  samBits(0xC0, 3, st.samV);
  emit('        LDA     FIELDN');
  emit(`        CMPA    #${FIELDS - STATIC}`);
  emit(`        BLS     C${ph}W`);
  // a lead-in field: the first display byte alternates, so every lead-in field is a changed picture
  // and MAME redraws (and so fills) both of its screen bitmaps
  emit('        ANDA    #1');
  emit('        STA     $0000');
  emit(`        BRA     C${ph}D`);
  emit(`C${ph}W    LDX     #$${ra.toString(16).toUpperCase()}`);
  emit(`        LDA     #$${rv.toString(16).toUpperCase()}`);
  emit(`        LDY     #$${sa.toString(16).toUpperCase()}`);
  emit(`        LDB     #$${sv.toString(16).toUpperCase()}`);
  emit(`        JSR     FIELD`);
  emit(`C${ph}D    DEC     FIELDN`);
  emit(`        BNE     C${ph}F`);
});
emit(`        LDA     #$FF
        STA     PHASE
HALT    BRA     HALT
`);

// FIELD: one field of both patterns. X/A restore state A, Y/B set state B.
emit(`; ---- FIELD: skip to the first swept line, then SWEEP and ALT
FIELD   TST     <$00            ; clear an HS flag left from before
        PSHS    X
        LDX     SKIPN
SKIP    SYNC
        TST     <$00
        LEAX    -1,X
        BNE     SKIP
        PULS    X`);
// SWEEP: line k restores A, then sets B at cycle c (the first instruction after SYNC starts at
// cycle 54 of the previous line, i.e. 3 cycles before this line; a store's write is its last cycle).
//   early form  SYNC; D(p); STA ,X; D(e); STB ,Y; TST   -> restore at cycle p, set at 4+p+e
//   late form   SYNC; D(p); STA ,X; TST; D(e); STB ,Y   -> set at 10+p+e (TST before the late set,
//               so it never clears the flag of this line's own HS fall at cycle 53)
emit('; SWEEP: every line starts in A and switches to B one cycle later than the line before');
for (let c = 6; c <= 52; c++) {
  emit(`        SYNC                    ; set at cycle ${c}`);
  if (c <= 45) {
    const p = (c % 2) ? 3 : 2, e = c - 4 - p;   // e is even and >= 0
    delay(p); emit('        STA     ,X'); delay(e); emit('        STB     ,Y'); emit('        TST     <$00');
  } else {
    const p = (c % 2) ? 3 : 2, e = c - 10 - p;
    delay(p); emit('        STA     ,X'); emit('        TST     <$00'); delay(e); emit('        STB     ,Y');
  }
}
// restore A before the gap so ALT starts from it
emit('        SYNC');
emit('        NOP');
emit('        STA     ,X');
emit('        TST     <$00');
emit(`        PSHS    X
        LDX     #${GAP}
GAPL    SYNC
        TST     <$00
        LEAX    -1,X
        BNE     GAPL
        PULS    X`);
// ALT: line pairs; the first line of a pair sets B at cycle c, the second restores A at cycle c+1.
//   early form  SYNC; D(q); STx; TST   -> write at cycle q (q >= 2)
//   late form   SYNC; TST; D(q); STx   -> write at cycle 6+q
emit('; ALT: lines alternate between switching to B and back to A, one cycle later each line');
for (let c = 2, k = 0; c <= 52; c++, k++) {
  const st = (k % 2) ? '        STA     ,X' : '        STB     ,Y';
  emit(`        SYNC                    ; ${k % 2 ? 'restore' : 'set'} at cycle ${c}`);
  if (c <= 45) { delay(c); emit(st); emit('        TST     <$00'); }
  else { emit('        TST     <$00'); delay(c - 6); emit(st); }
}
emit(`        SYNC
        NOP
        STA     ,X              ; leave the field in state A
        TST     <$00
        RTS

PAL     FCB     ${PALETTE.join(',')}
; interrupt vectors: never taken (IRQ and FIRQ stay masked), but defined
SWIH    RTI
        ORG     $FFF2
        FDB     SWIH,SWIH,SWIH,SWIH,SWIH,SWIH
        ORG     $FFFE
        FDB     RESET
        END     RESET`);

// write raster.asm (run as a script, or from spec.raster before a MAME comparison)
function write() { writeAtomic(path.join(__dirname, 'raster.asm'), L.join('\n') + '\n'); }
if (require.main === module) write();
module.exports = { cases: cases.map(([name, , , , effect], i) => ({ name, phase: i + 1, noEffect: effect === 'no effect' })), FIELDS, write };
