#!/usr/bin/env node
// Writes the Help page's list of machines (help/index.html, between its machines markers) from the data: every model
// the machine menu offers, in the menu's sections with their subtitles (js/machines/menu.js GROUPS, SUBTITLES), what
// each model is (DESCRIPTIONS) and the ROMs it takes, by the names Your ROMs uses (each socket's label, whether it is
// needed, and its usual file names, from js/machines/profiles.js). The machine menu's "Which one is mine? ↗" links here.
//
//   node tools/gen-machine-help.js           write help/index.html
//   node tools/gen-machine-help.js --check   exit 1 if it is out of date (tests/machine-menu.test.js runs this too)
const fs = require('fs'), path = require('path');

const FILE = path.join(__dirname, '..', 'help', 'index.html');
const START = '<!-- machines:start (generated by tools/gen-machine-help.js) -->', END = '<!-- machines:end -->';
const esc = (t) => String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// the generated part -> HTML (async: the menu's data is an ES module)
async function machinesHtml() {
  const { availableProfiles } = require('../tests/load')();
  const { groupProfiles, SUBTITLES, DESCRIPTIONS } = await import('../js/machines/menu.js');
  const out = [START];
  for (const [name, list] of groupProfiles(availableProfiles())) {
    out.push(`    <h3>${esc(name)}</h3>`, `    <p class="muted">${esc(SUBTITLES[name])}</p>`, '    <dl>');
    for (const p of list) {
      const roms = p.roms.map((s) => `${esc(s.label)} (${s.required ? 'needed' : 'optional'}; usually ${s.files.map((f) => `<code>${esc(f)}</code>`).join(' or ')})`);
      out.push(`      <dt id="machine-${p.id}">${esc(p.name)}</dt>`,
        `      <dd>${esc(DESCRIPTIONS[p.id].text.replace(/^./, (c) => c.toUpperCase()))}. ROMs: ${roms.join(', ')}.</dd>`);
    }
    out.push('    </dl>');
  }
  out.push(`    ${END}`);
  return out.join('\n');
}
function splice(html, part) {
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error('help/index.html: machines markers not found');
  return html.slice(0, a) + part + html.slice(b + END.length);
}
async function expected() { return splice(fs.readFileSync(FILE, 'utf8'), await machinesHtml()); }

module.exports = { machinesHtml, expected, FILE };

if (require.main === module) {
  (async () => {
    const want = await expected();
    if (process.argv.includes('--check')) {
      if (want !== fs.readFileSync(FILE, 'utf8')) { console.error('help/index.html: the list of machines is out of date (node tools/gen-machine-help.js)'); process.exitCode = 1; }
      return;
    }
    fs.writeFileSync(FILE, want);
    console.log('wrote help/index.html');
  })();
}
