#!/usr/bin/env node
// Build CLOADM's clean-room BASIC for the Dragon 64 (docs/clean-room-basic.md): assemble basic/d64basic.asm with
// the repository's own assembler into a 16K image for $8000-$BFFF.
//   node tools/build-basic.js                   write the image to basic/cloadm-basic-d64.rom (committed: tests/basic-rom-file.test.js
//                                               checks it is what the source builds) and print its size
//   node tools/build-basic.js --out FILE        write it to FILE instead (--out d64_1.rom for --roms, which takes a
//                                               file by name: the committed one has its own, so it is never taken
//                                               for a dump of the original)
// require('./build-basic.js').buildBasic() -> { rom, symbols, listing, used } for the tests (nothing is written);
// buildBasic({ edit }) builds a mutant: edit(file, text) -> the text assembled for each source file in basic/.
// The keyword table (basic/tokens.json) becomes the generated include "tokens.inc": the T_ token equates, the two
// keyword tables the cruncher and LIST use, and the statement and function dispatch tables; tools/basic-consts.js
// gives the generated includes "mathconst.inc", the mathematical constants, and "sine.inc", CIRCLE's sine table.
const fs = require('fs'), path = require('path');
const DIR = path.join(__dirname, '..', 'basic');
const ROM_AT = 0x8000, ROM_SIZE = 0x4000;
const ROM_FILE = path.join(DIR, 'cloadm-basic-d64.rom');

// "STR$" -> T_STRS, "TAB(" -> T_TAB, operators by name; a function's symbol ends in F (T_STRSF)
const OPS = { "'": 'APOS', '+': 'PLUS', '-': 'MINUS', '*': 'MUL', '/': 'DIV', '^': 'POW', '>': 'GT', '=': 'EQ', '<': 'LT' };
const symName = (w) => 'T_' + (OPS[w] || w.replace(/\$/g, 'S').replace(/\(/g, ''));
const hex = (v) => '$' + v.toString(16).toUpperCase().padStart(2, '0');

function tokensInc(json) {
  const out = ['* generated by tools/build-basic.js from basic/tokens.json: do not edit'];
  const assign = (list) => { let next = 0x80; return list.map((e) => { const t = e.token != null ? Number(e.token) : next; next = t + 1; return { ...e, t }; }); };
  const st = assign(json.statements), fn = assign(json.functions);
  for (const list of [st, fn]) {
    const seen = new Set();
    for (const e of list) {
      if (seen.has(e.t) || e.t < 0x80 || e.t > 0xFE) throw new Error(`basic/tokens.json: bad or repeated token for ${e.word}`);
      seen.add(e.t);
    }
  }
  for (const e of st) out.push(`${symName(e.word).padEnd(8)} EQU     ${hex(e.t)}`);
  for (const e of fn) out.push(`${(symName(e.word) + 'F').padEnd(8)} EQU     ${hex(e.t)}`);
  const last = (l) => Math.max(...l.map((e) => e.t));
  // T_SLAST: the last statement token; the words that are not statements ("stmt": false) have no dispatch entry,
  // and one inside the statements' range runs UNIMPL
  const stmts = st.filter((e) => e.stmt !== false);
  out.push(`T_LAST   EQU     ${hex(last(st))}`, `T_SLAST  EQU     ${hex(last(stmts))}`, `TF_LAST  EQU     ${hex(last(fn))}`);
  // a keyword table: the words in token order from $80, each ending in a letter with bit 7 set (FCS); a word's
  // token is its place in the table, so a token with no word between two others is one $FF byte (never typed)
  const table = (label, list) => {
    out.push(label);
    for (let t = 0x80; t <= last(list); t++) {
      const e = list.find((x) => x.t === t);
      out.push(e ? `        FCS     "${e.word}"` : '        FCB     $FF');
    }
    out.push('        FCB     0');
  };
  table('KWSTMT', st);
  table('KWFUNC', fn);
  const dispatch = (label, list) => {
    out.push(label);
    for (let t = 0x80; t <= last(list); t++) {
      const e = list.find((x) => x.t === t);
      out.push(`        FDB     ${(e && e.handler) || 'UNIMPL'}`);
    }
  };
  dispatch('STMTDS', stmts);
  dispatch('FUNCDS', fn);
  return out.join('\n') + '\n';
}

function buildBasic({ defines = {}, edit = (file, text) => text } = {}) {
  const Emu = require('../tests/load.js')();
  const json = JSON.parse(fs.readFileSync(path.join(DIR, 'tokens.json'), 'utf8'));
  const gen = { 'tokens.inc': tokensInc(json), 'mathconst.inc': require('./basic-consts.js').mathConstsInc(), 'sine.inc': require('./basic-consts.js').sineInc() };
  const include = (name) => gen[name] || (fs.existsSync(path.join(DIR, name)) ? edit(name, fs.readFileSync(path.join(DIR, name), 'utf8')) : null);
  const res = Emu.assemble(edit('d64basic.asm', fs.readFileSync(path.join(DIR, 'd64basic.asm'), 'utf8')), '6809', { include, defines });
  if (!res.ok) throw new Error('basic/d64basic.asm:\n' + res.errors.map((e) => (typeof e === 'string' ? e : JSON.stringify(e))).join('\n'));
  const rom = new Uint8Array(ROM_SIZE).fill(0xFF);
  const owner = new Int32Array(ROM_SIZE).fill(-1);
  res.segments.forEach((s, i) => {
    if (s.addr < ROM_AT || s.addr + s.data.length > ROM_AT + ROM_SIZE) throw new Error(`basic: code at $${s.addr.toString(16)} (${s.data.length} bytes) is outside $8000-$BFFF`);
    for (let k = 0; k < s.data.length; k++) {
      const o = s.addr - ROM_AT + k;
      if (owner[o] >= 0) throw new Error(`basic: two pieces of code overlap at $${(s.addr + k).toString(16)}`);
      owner[o] = i;
      rom[o] = s.data[k];
    }
  });
  const used = owner.reduce((n, o) => n + (o >= 0 ? 1 : 0), 0);
  // the system RAM block and the direct page must not run into the buffers after them
  if (res.symbols.get('SYSEND') > res.symbols.get('LINBUF')) throw new Error('basic: the system RAM ($0100 on) runs into LINBUF');
  // the direct page's regions end at or below the fixed addresses after them (d64basic.asm)
  for (const [end, at] of [['DPR1', 'CURPOS'], ['DPR2', 'BLINK'], ['DPR3', 'KEYDLY']]) {
    if (res.symbols.get(end) > res.symbols.get(at)) throw new Error(`basic: the direct-page variables before ${at} run into it (move the split at ${end})`);
  }
  if (res.symbols.get('DPEND') > res.symbols.get('ZTRAMP')) throw new Error('basic: the direct page is full (its variables reach the two-byte calls at ZTRAMP)');
  return { rom, symbols: res.symbols, listing: res.listing, used };
}
module.exports = { buildBasic, tokensInc, ROM_FILE };

if (require.main === module) {
  const i = process.argv.indexOf('--out');
  const b = buildBasic();
  const end = b.symbols.get('ROMEND');
  console.log(`basic: ${b.used} bytes used of ${ROM_SIZE}${end != null ? `, code ends at $${end.toString(16).toUpperCase()}` : ''}`);
  const out = i > 0 ? process.argv[i + 1] : ROM_FILE;
  fs.writeFileSync(out, b.rom);
  console.log(`written ${path.relative(process.cwd(), out) || out}`);
}
