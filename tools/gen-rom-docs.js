#!/usr/bin/env node
// Generates docs/roms.md from the profiles (js/machines/profiles.js): every machine's ROM sockets,
// whether each is required, its size, usual file names and aliases, the CRC32 of each known-good dump,
// and the combined-file option; then the disk cartridges' ROMs.
//
//   node tools/gen-rom-docs.js           write docs/roms.md
//   node tools/gen-rom-docs.js --check   exit 1 if docs/roms.md is out of date (tests/romdocs.test.js)
//   --out FILE                           another file instead of docs/roms.md
// It also writes the short per-machine table into README.md and the /roms page (roms/index.html) between their
// rom-table markers.
const fs = require('fs'), path = require('path');
const Emu = require('../tests/load')();

const outArg = process.argv.indexOf('--out');
const OUT = outArg > 0 ? path.resolve(process.argv[outArg + 1]) : path.join(__dirname, '../docs/roms.md');
const kb = (n) => `${n / 1024}K`;
const code = (list) => list.map((x) => `\`${x}\``).join(', ');

function combined(p) {
  if (p.roms.length !== 2) return null;
  const [a, b] = [...p.roms].sort((x, y) => (x.bank - y.bank) || (x.at - y.at));
  return `one ${kb(a.size + b.size)} file holding ${a.label} followed by ${b.label}`;
}

function socketTable(roms) {
  const rows = ['| Socket | Needed | Size | Usual file names | Also known as | Known-good CRC32 |', '|---|---|---|---|---|---|'];
  for (const s of roms) {
    rows.push(`| ${s.label} | ${s.required ? 'Required' : 'Optional'} | ${kb(s.size)} | ${code(s.files)} | ${s.aliases.length ? code(s.aliases) : '–'} | ${s.crcs.length ? code(s.crcs) : 'none yet'} |`);
  }
  return rows.join('\n');
}

// the short per-machine table, shared with the README
function machineTable() {
  const rows = ['| Machine | Required | Optional | Total size |', '|---|---|---|---|'];
  for (const p of Object.values(Emu.profiles)) {
    const req = p.roms.filter((s) => s.required), opt = p.roms.filter((s) => !s.required);
    rows.push(`| ${p.name} | ${req.map((s) => `${s.label} (${kb(s.size)})`).join(', ') || '–'} | ${opt.map((s) => `${s.label} (${kb(s.size)})`).join(', ') || '–'} | ${kb(p.roms.reduce((t, s) => t + s.size, 0))} |`);
  }
  return rows.join('\n');
}
const README = path.join(__dirname, '../README.md');
const START = '<!-- rom-table:start (generated by tools/gen-rom-docs.js) -->', END = '<!-- rom-table:end -->';
function readmeWith(table) {
  const r = fs.readFileSync(README, 'utf8'), a = r.indexOf(START), b = r.indexOf(END);
  if (a < 0 || b < a) throw new Error('README.md: rom-table markers not found');
  return r.slice(0, a + START.length) + '\n' + table + '\n' + r.slice(b);
}

// the same table in HTML for the /roms page
const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;');
function machineTableHtml() {
  const rows = ['<table class="plain">', '<thead><tr><th>Machine</th><th>Required</th><th>Optional</th><th>Total size</th><th>Usual file names</th></tr></thead>', '<tbody>'];
  // each socket's usual names (alternatives joined by "or"), required sockets first
  const names = (p) => [...p.roms.filter((s) => s.required), ...p.roms.filter((s) => !s.required)]
    .map((s) => s.files.map((f) => `<code>${esc(f)}</code>`).join(' or ') + (s.required ? '' : ' (optional)')).join(' + ');
  for (const p of Object.values(Emu.profiles)) {
    const req = p.roms.filter((s) => s.required), opt = p.roms.filter((s) => !s.required);
    const list = (l) => esc(l.map((s) => `${s.label} (${kb(s.size)})`).join(', ') || '–');
    rows.push(`<tr><td>${esc(p.name)}</td><td>${list(req)}</td><td>${list(opt)}</td><td>${kb(p.roms.reduce((t, s) => t + s.size, 0))}</td><td>${names(p)}</td></tr>`);
  }
  rows.push('</tbody>', '</table>');
  return rows.join('\n');
}
const ROMS_PAGE = path.join(__dirname, '../roms/index.html');
function romsPageWith(table) {
  const r = fs.readFileSync(ROMS_PAGE, 'utf8'), a = r.indexOf(START), b = r.indexOf(END);
  if (a < 0 || b < a) throw new Error('roms/index.html: rom-table markers not found');
  return r.slice(0, a + START.length) + '\n' + table + '\n' + r.slice(b);
}

function generate() {
  const out = [];
  out.push('# ROMs', '');
  out.push('<!-- Generated by tools/gen-rom-docs.js from js/machines/profiles.js. Do not edit by hand. -->', '');
  out.push('CLOADM needs the original ROM chips\' contents to run BASIC. They are copyrighted by Microsoft, Tandy,',
    'Dragon Data and others, so CLOADM doesn\'t include them and never downloads them: dump your own, or see',
    '[where to get ROMs](https://cloadm.dev/roms/) (check your rights first).',
    'Without ROMs, a built-in stub firmware runs machine-code programs.', '');
  out.push('Drop the files (any names, a folder or a ZIP) on the page. CLOADM recognises ROMs by their contents: a file',
    'whose CRC32 matches a known-good dump below is **verified**, and one drop sets up every machine it fits. A file',
    'whose contents aren\'t known is still loaded when its name and size match a socket (or, for the machine in use,',
    'its size alone), and shows as **loaded, not a known dump**. ROMs stay in the browser that loaded them.', '');
  out.push('> **Known bugs:** Color BASIC 1.0 and 1.1 (`bas10.rom`, `bas11.rom`) and Extended Color BASIC 1.0',
    '> (`extbas10.rom`) have known bugs; prefer `bas12.rom`/`bas13.rom` and `extbas11.rom` where you have them.', '');
  out.push('## Machines', '', machineTable(), '');
  for (const p of Object.values(Emu.profiles)) {
    out.push(`### ${p.name}`, '');
    out.push(socketTable(p.roms), '');
    const c = combined(p);
    if (c) out.push(`A combined image also works: ${c}.`, '');
  }
  out.push('## Disk cartridges', '');
  out.push('Disk BASIC lives in the disk cartridge, not in the computer. CLOADM recognises these ROMs and',
    'plugs them into the disk cartridge when a disk is mounted (the CP-400 one is kept until that model exists);',
    'they never make a machine bootable.', '');
  for (const c of Object.values(Emu.cartridgeRoms)) {
    out.push(`### ${c.name} (${c.for})`, '');
    out.push(socketTable(c.roms), '');
  }
  out.push('## Names not recognised on purpose', '');
  out.push('`d200rom1.rom` and `d200rom2.rom` (names used in some ROM sets for the Dragon 200) are not aliases: it isn\'t',
    'confirmed which chips they are. This costs nothing for known dumps, which are recognised by their contents',
    'whatever their names. If you own a Dragon 200 and its ROMs aren\'t recognised, run the ROM self-test and send',
    'the CRC32s from its report (it never contains ROM data), so they can be added as known-good dumps.', '');
  out.push('## Not supported', '');
  out.push('The Alice 32 and Alice 90 are different machines from the Matra Alice (MC-10 clone); their ROMs don\'t',
    'fit it.', '');
  return out.join('\n');
}

const text = generate(), readme = readmeWith(machineTable()), romsPage = romsPageWith(machineTableHtml());
const rel = (f) => path.relative(process.cwd(), f);
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  let stale = [];
  if (cur !== text) stale.push(rel(OUT));
  if (outArg < 0 && fs.readFileSync(README, 'utf8') !== readme) stale.push('README.md (ROM table)');
  if (outArg < 0 && fs.readFileSync(ROMS_PAGE, 'utf8') !== romsPage) stale.push('roms/index.html (ROM table)');
  if (stale.length) { console.error(`${stale.join(' and ')} out of date: run node tools/gen-rom-docs.js`); process.exitCode = 1; return; }
  console.log(`${rel(OUT)} is up to date`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  if (outArg < 0) { fs.writeFileSync(README, readme); fs.writeFileSync(ROMS_PAGE, romsPage); }
  console.log(`wrote ${rel(OUT)}${outArg < 0 ? ', the README ROM table and the /roms page table' : ''}`);
}
