#!/usr/bin/env node
// The <link rel="modulepreload"> list for /play/, generated from the module graph and checked by a test.
//
//   node tools/gen-page-preload.js          rewrite the list in play/index.html
//   node tools/gen-page-preload.js --check  exit 1 if it is out of date (tests/pagegraph.test.js runs this)
//
// Why: without it the browser learns about a module only when the module that imports it has arrived, so an
// import graph N deep costs N round trips before the last module is even requested. modulepreload tells the
// browser about all of them from the HTML, so they are fetched in parallel while the first one is parsed.
// Nothing about what runs changes - only when the request is made.
//
// Only STATIC imports are followed (and `export ... from`). A module reached only through `import()` is left
// out on purpose: preloading it would undo the lazy import that keeps it off the startup path.
const fs = require('fs'), path = require('path');

const ROOT = path.join(__dirname, '..');
const PAGE = path.join(ROOT, 'play/index.html');
const ENTRY = 'js/ui/main.js';
const START = '<!-- modulepreload:start (generated by tools/gen-page-preload.js; do not edit) -->';
const END = '<!-- modulepreload:end -->';

// the static module graph, in the order the browser would discover it (depth first, imports before the importer)
function staticGraph(entry) {
  const order = [], seen = new Set();
  const visit = (rel) => {
    const abs = path.join(ROOT, rel);
    if (seen.has(abs) || !fs.existsSync(abs)) return;
    seen.add(abs);
    const text = fs.readFileSync(abs, 'utf8');
    for (const m of text.matchAll(/(?:^|\n)\s*(?:import|export)\s[^'"]*?from\s+['"]([^'"]+)['"]/g)) {
      if (!m[1].startsWith('.')) continue;
      visit(path.relative(ROOT, path.resolve(path.dirname(abs), m[1])));
    }
    order.push(rel);
  };
  visit(entry);
  return order;
}

function list(entry = ENTRY) {
  const order = staticGraph(entry);
  // the entry itself is already requested by its own <script> tag: preloading it would only repeat the request
  return order.filter((f) => f !== entry);
}

function block(files) {
  return [START, ...files.map((f) => `<link rel="modulepreload" href="${f}">`), END].join('\n');
}

const html = fs.readFileSync(PAGE, 'utf8');
const i = html.indexOf(START), j = html.indexOf(END);
const files = list();
const next = block(files);

if (process.argv.includes('--check')) {
  if (i < 0 || j < 0) { console.error(`play/index.html: missing the modulepreload markers (${START} ... ${END})`); process.exitCode = 1; return; }
  const now = html.slice(i, j + END.length);
  if (now === next) { console.log(`play/index.html: ${files.length} modulepreload links, up to date`); process.exitCode = 0; return; }
  const nowLines = now.split('\n'), nextLines = next.split('\n');
  const add = nextLines.filter((l) => !nowLines.includes(l)), del = nowLines.filter((l) => !nextLines.includes(l));
  console.error(`play/index.html: modulepreload list is out of date (run node tools/gen-page-preload.js)\n  missing: ${add.join(' ') || '-'}\n  stale:   ${del.join(' ') || '-'}`);
  process.exitCode = 1;
  return;
}

if (i < 0 || j < 0) { console.error(`play/index.html: missing the modulepreload markers`); process.exitCode = 1; return; }
fs.writeFileSync(PAGE, html.slice(0, i) + next + html.slice(j + END.length));
console.log(`play/index.html: ${files.length} modulepreload links written`);
