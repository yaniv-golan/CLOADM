// WYRMFIRE's credits screen: C on the title opens it, and it carries Freedoom's licence notice. The strings come from
// two places and this checks both: the two level lines are the LEVEL DISK's own (the converter writes a CREDITS entry
// into the HGA1 asset block, so a disk made from the person's own WAD says "LEVEL DATA: YOUR OWN WAD" instead), and
// the two engine lines are the engine's own code (src/native.c's credits()). Read from the RENDERED page by decoding
// the engine's glyphs, exactly as WYRMFIRE's own test/harness/credits.cjs does -- a text screen reader cannot see this
// page, which is drawn in GM7 graphics.
//
// The glyph table is tests/wyrmfire-font.json, generated by tools/wyrmfire-vendor.js from the pinned commit's
// src/font.h, so the decoder cannot drift from the engine that drew the pixels.
//
// No id Software data is involved: the disk is the pinned Freedoom one.
const fs = require('fs'), path = require('path');
const Emu = require('./load')();
const { WYRMFIRE_PIN: PIN } = require('../js/wyrmfire/pin.js');

const ROOT = path.join(__dirname, '..');
let fail = 0;
const check = (name, cond, detail = '') => { if (!cond) { fail++; console.log(`FAIL ${name} ${detail}`); } else console.log(`ok   ${name} ${detail}`); };
const J = JSON.stringify;

const FONT = JSON.parse(fs.readFileSync(path.join(ROOT, PIN.files.font.path), 'utf8'));
const glyph = (code) => FONT.bytes.slice((code - FONT.first) * 9, (code - FONT.first) * 9 + 9);
// One 32-column row at page row `y`: each cell is a column of 9 bytes, 32 bytes apart (the engine's 256x192 page).
function rowText(read, base, y) {
  return Array.from({ length: 32 }, (_, c) => {
    const col = Array.from({ length: 9 }, (_, i) => read(base + (y << 5) + c + (i << 5)));
    if (col.every((v) => v === 0)) return ' ';
    for (let ch = 32; ch < 91; ch++) if (glyph(ch).every((v, i) => v === col[i])) return String.fromCharCode(ch);
    return '?';
  }).join('').trimEnd();
}

// the rows the credits screen draws on (src/native.c: y starts at 64, 12 per line; the heading at 40, the hint at 160)
const ROWS = [64, 76, 88, 100, 112, 124];
const ENGINE = new Uint8Array(fs.readFileSync(path.join(ROOT, PIN.files.engine.path)));
const LEVEL = new Uint8Array(fs.readFileSync(path.join(ROOT, PIN.files.level.path)));

// Boot WYRMFIRE, hold C through the title until the credits screen is up, then read its rows.
function creditsScreen() {
  const s = new Emu.Session({});
  s.startWyrmfire(ENGINE, LEVEL.slice(), {});
  const m = s.personMachine, read = (a) => s.readByte(a, m);
  let rows = null;
  for (let f = 0; f < 3000; f++) {
    m.setKey('C', true); s.runFrames(1);
    if (read(0x200)) return { started: true };                        // the game started without the credits
    if (rowText(read, m.sam.displayBase, 40).trim() === 'CREDITS') { s.runFrames(50); rows = ROWS.map((y) => rowText(read, m.sam.displayBase, y)); break; }
  }
  m.setKey('C', false);
  return { started: false, rows, waiting: !read(0x200) };
}

{
  const r = creditsScreen();
  check('C on the title opens the credits screen (and the game waits for ENTER, it does not start)', !r.started && r.rows && r.waiting, J({ started: r.started, waiting: r.waiting }));
  const shown = (r.rows || []).map((t) => t.trim()).filter(Boolean);
  console.log('  the screen, as decoded:\n' + (r.rows || []).map((t, i) => `    y=${ROWS[i]} |${t.padEnd(32)}|`).join('\n'));
  // The four strings the licence needs on screen. "WYRMFIRE  GPL-3.0" has TWO spaces (src/native.c).
  for (const want of ['LEVEL DATA: FREEDOOM (BSD)', 'MODIFIED FOR THE DRAGON 64', 'WYRMFIRE  GPL-3.0', 'NOT AFFILIATED WITH ID SOFTWARE']) {
    check(`the credits screen shows "${want}"`, shown.includes(want), J(shown));
  }
  check('... and it shows those four and no other line (the disk\'s two, then the engine\'s two)',
    shown.length === 4, J(shown));
}

// THE MUTANT, on the shipped bytes: the same check, run on an engine whose "NOT AFFILIATED WITH ID SOFTWARE" string is
// changed in the binary (one word, same length, so nothing else can shift). If the check were reading anything but the
// engine's own text it would still pass; it must fail. This is the mutant the licence notice really needs: an engine
// shipped with the wrong trademark line has to be caught before it goes out, not after.
{
  const patched = Buffer.from(ENGINE);
  const at = patched.indexOf(Buffer.from('NOT AFFILIATED WITH ID SOFTWARE'));
  check('the vendored engine carries the trademark line as a literal string (so this mutant patches the real bytes)',
    at > 0, J({ offset: at }));
  if (at > 0) patched.write('NOT AFFILIATED WITH ID SOFTWORK', at);
  const s = new Emu.Session({});
  s.startWyrmfire(new Uint8Array(patched), LEVEL.slice(), {});
  const m = s.personMachine, read = (a) => s.readByte(a, m);
  let rows = null;
  for (let f = 0; f < 3000; f++) {
    m.setKey('C', true); s.runFrames(1);
    if (read(0x200)) break;
    if (rowText(read, m.sam.displayBase, 40).trim() === 'CREDITS') { s.runFrames(50); rows = ROWS.map((y) => rowText(read, m.sam.displayBase, y)); break; }
  }
  m.setKey('C', false);
  const shown = (rows || []).map((t) => t.trim()).filter(Boolean);
  check('MUTANT (the engine binary patched): the trademark line is wrong on the rendered page, and the check fails',
    rows && !shown.includes('NOT AFFILIATED WITH ID SOFTWARE') && shown.some((t) => /SOFTWORK/.test(t)), J(shown));
}

if (fail) { console.log(`${fail} FAILED`); process.exitCode = 1; } else console.log('all credits checks passed');
